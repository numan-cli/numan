//! Hook event allow-list and generated Nushell hook integration (issue #16).

use anyhow::{bail, Result};
use std::collections::BTreeMap;
use std::path::Path;

use crate::state::hook_profile::{HookBindingRecord, HookProfile};
use crate::util::fs_safety::OWNERSHIP_MARKER;

/// Deliberately small allow-list of Nushell hook events whose composition and
/// acceptance behavior can be proven. Unknown events are rejected at parse time.
pub const ALLOWED_HOOK_EVENTS: &[&str] = &["pre_prompt", "pre_execution", "env_change"];

pub fn is_allowed_event(event: &str) -> bool {
    ALLOWED_HOOK_EVENTS.contains(&event)
}

/// Generate the Numan-owned vendor-autoload file for an active hook profile.
/// The file verifies that its embedded profile matches the atomic state file
/// before registering callbacks. A crash between the two replacements disables
/// Numan hooks until a later `numan hook` command repairs the projection.
pub fn generate_hook_autoload_content(
    profile: &HookProfile,
    profile_path: &Path,
) -> Result<String> {
    let expected_profile = serde_json::to_string(profile)?;
    let mut out = String::from(OWNERSHIP_MARKER);
    out.push_str("\n# Generated by Numan. Do not edit.\n");
    out.push_str(&format!(
        "let __numan_profile = (try {{ open {} }} catch {{ {{ bindings: [] }} }})\n",
        nu_path_literal(&profile_path.to_string_lossy())?
    ));
    out.push_str(&format!(
        "let __numan_expected = ({} | from json)\n",
        nu_raw_string_literal(&expected_profile)
    ));
    out.push_str(
        "let __numan_expected_executable = ($__numan_expected.nu_executable? | default \"\")\n",
    );
    out.push_str("let __numan_runtime_executable = ($nu.current-exe | path expand)\n");
    out.push_str("let __numan_runtime_version = (version | get version)\n");
    out.push_str("if $__numan_profile == $__numan_expected and $__numan_runtime_executable == ($__numan_expected_executable | path expand) and $__numan_runtime_version == $__numan_expected.nu_version {\n");
    out.push_str("  mut __numan_hooks = ($env.config.hooks? | default {})\n");

    let mut list_hooks: BTreeMap<&str, Vec<String>> = BTreeMap::new();
    let mut env_hooks: BTreeMap<&str, Vec<String>> = BTreeMap::new();
    for binding in &profile.bindings {
        let rendered = render_binding(binding)?;
        if binding.event == "env_change" {
            let key = binding.filter.as_deref().ok_or_else(|| {
                anyhow::anyhow!(
                    "env_change hook '{}' needs filter naming the environment variable",
                    binding.id
                )
            })?;
            if !key
                .chars()
                .next()
                .is_some_and(|character| character.is_ascii_alphabetic() || character == '_')
                || !key
                    .chars()
                    .all(|character| character.is_ascii_alphanumeric() || character == '_')
            {
                bail!(
                    "env_change hook '{}' has invalid environment-variable filter '{}'; use letters, digits, and underscore",
                    binding.id,
                    key
                );
            }
            env_hooks.entry(key).or_default().push(rendered);
        } else {
            list_hooks
                .entry(binding.event.as_str())
                .or_default()
                .push(rendered);
        }
    }

    for (event, bindings) in list_hooks {
        out.push_str(&format!(
            "  let __numan_existing = ($__numan_hooks.{event}? | default [])\n"
        ));
        out.push_str(&format!(
            "  $__numan_hooks = ($__numan_hooks | upsert {event} ($__numan_existing ++ [{}]))\n",
            bindings.join(", ")
        ));
    }

    if !env_hooks.is_empty() {
        out.push_str("  mut __numan_existing_env = ($__numan_hooks.env_change? | default {})\n");
        for (variable, bindings) in env_hooks {
            out.push_str(&format!(
                "  let __numan_existing_{variable} = ($__numan_existing_env.{variable}? | default [])\n"
            ));
            out.push_str(&format!(
                "  $__numan_existing_env = ($__numan_existing_env | upsert {variable} ($__numan_existing_{variable} ++ [{}]))\n",
                bindings.join(", ")
            ));
        }
        out.push_str(
            "  $__numan_hooks = ($__numan_hooks | upsert env_change $__numan_existing_env)\n",
        );
    }

    out.push_str("  $env.config = ($env.config | upsert hooks $__numan_hooks)\n");
    out.push_str("}\n");
    Ok(out)
}

fn render_binding(binding: &HookBindingRecord) -> Result<String> {
    if !is_allowed_event(&binding.event) {
        bail!(
            "hook '{}' uses unsupported event '{}'; allowed events: {}",
            binding.id,
            binding.event,
            ALLOWED_HOOK_EVENTS.join(", ")
        );
    }
    if binding.handler.is_empty() {
        bail!("hook '{}' has an empty handler path", binding.id);
    }
    let source = format!("source {}", nu_path_literal(&binding.handler)?);
    let filter = binding.filter.as_deref().unwrap_or_default();
    let guarded = if binding.event != "env_change" && !filter.is_empty() {
        format!("if ({filter}) {{ {source} }}")
    } else {
        source.clone()
    };
    Ok(match binding.event.as_str() {
        "pre_prompt" | "pre_execution" => format!("{{|| {guarded} }}"),
        "env_change" => "{|before, after| ".to_string() + &source + " }",
        _ => unreachable!("allow-list checked above"),
    })
}

fn nu_path_literal(value: &str) -> Result<String> {
    if value.contains('\0') {
        bail!("Nushell paths cannot contain NUL bytes");
    }
    let value = if cfg!(windows) {
        value.replace('\\', "/")
    } else {
        value.to_string()
    };
    Ok(nu_raw_string_literal(&value))
}

fn nu_raw_string_literal(value: &str) -> String {
    let mut hashes = 1;
    loop {
        let closing = format!("'{}", "#".repeat(hashes));
        if !value.contains(&closing) {
            let delimiter = "#".repeat(hashes);
            return format!("r{delimiter}'{value}'{delimiter}");
        }
        hashes += 1;
    }
}

#[cfg(test)]
mod generation_tests {
    use super::*;

    fn record(event: &str, filter: Option<&str>) -> HookBindingRecord {
        HookBindingRecord {
            id: "owner/tool/pre-prompt".to_string(),
            event: event.to_string(),
            handler: "C:/numan/packages/modules/owner/tool/hooks/run.nu".to_string(),
            filter: filter.map(str::to_string),
            package_id: "owner/tool".to_string(),
            activated_at: "now".to_string(),
        }
    }

    #[test]
    fn generated_file_keeps_ownership_marker_and_user_hooks() {
        let profile = HookProfile {
            bindings: vec![record("pre_prompt", None)],
            ..HookProfile::default()
        };
        let generated = generate_hook_autoload_content(
            &profile,
            Path::new("C:/numan/nu_state/hook_profile.json"),
        )
        .unwrap();
        assert!(generated.starts_with(OWNERSHIP_MARKER));
        assert!(generated.contains("($__numan_existing ++ [{|| source"));
        assert!(generated.contains("upsert hooks $__numan_hooks"));
        assert!(generated.contains("if $__numan_profile == $__numan_expected"));
        assert!(generated.contains(
            "$__numan_runtime_executable == ($__numan_expected_executable | path expand)"
        ));
        assert!(generated.contains("default \"\""));
        assert!(generated.contains("$__numan_runtime_version == $__numan_expected.nu_version"));
    }

    #[test]
    fn env_change_requires_a_variable_selector() {
        let profile = HookProfile {
            bindings: vec![record("env_change", None)],
            ..HookProfile::default()
        };
        assert!(generate_hook_autoload_content(&profile, Path::new("profile.json")).is_err());
    }

    #[test]
    fn display_output_is_rejected_until_it_can_be_composed_safely() {
        let profile = HookProfile {
            bindings: vec![record("display_output", Some("true"))],
            ..HookProfile::default()
        };
        assert!(generate_hook_autoload_content(&profile, Path::new("profile.json")).is_err());
    }

    #[test]
    fn path_literal_preserves_escape_like_backslashes_in_raw_strings() {
        let literal = nu_path_literal(r"/tmp/hooks/\nhandler.nu").unwrap();
        if cfg!(windows) {
            assert_eq!(literal, r"r#'/tmp/hooks//nhandler.nu'#");
        } else {
            assert_eq!(literal, r"r#'/tmp/hooks/\nhandler.nu'#");
        }
        assert!(nu_path_literal("/tmp/\0handler.nu").is_err());
    }

    #[test]
    #[ignore = "requires a real Nushell binary on PATH or NUMAN_TEST_NU"]
    fn generated_hook_runtime_preserves_user_hooks_and_runs_owned_handler() {
        let nu = std::env::var_os("NUMAN_TEST_NU")
            .map(std::path::PathBuf::from)
            .unwrap_or_else(|| {
                let output = std::process::Command::new("nu")
                    .args(["-n", "-c", "$nu.current-exe"])
                    .output()
                    .expect("Nushell must be available on PATH for the ignored runtime test");
                assert!(
                    output.status.success(),
                    "Nu failed to report its executable path: {}",
                    String::from_utf8_lossy(&output.stderr)
                );
                std::path::PathBuf::from(String::from_utf8_lossy(&output.stdout).trim().to_string())
            });
        let version_output = std::process::Command::new(&nu)
            .args(["-n", "-c", "version | get version"])
            .output()
            .expect("Nushell must report its version");
        assert!(
            version_output.status.success(),
            "Nu failed to report its version: {}",
            String::from_utf8_lossy(&version_output.stderr)
        );
        let nu_version = String::from_utf8_lossy(&version_output.stdout)
            .trim()
            .to_string();
        let dir = tempfile::tempdir().unwrap();
        let root = dir.path();
        let profile_path = root.join("nu_state/hook_profile.json");
        let handler_path = root.join("handler.nu");
        let filtered_handler_path = root.join("filtered-handler.nu");
        let env_handler_path = root.join("env-handler.nu");
        let generated_path = root.join("numan-hooks.nu");
        std::fs::write(&handler_path, "print 'numan-handler-ran'\n").unwrap();
        std::fs::write(&filtered_handler_path, "print 'filtered-handler-ran'\n").unwrap();
        std::fs::write(&env_handler_path, "print 'env-change-handler-ran'\n").unwrap();
        let profile = HookProfile {
            nu_executable: Some(nu.to_string_lossy().replace('\\', "/")),
            nu_version: Some(nu_version),
            bindings: vec![
                HookBindingRecord {
                    id: "owner/tool/prompt".into(),
                    event: "pre_prompt".into(),
                    handler: handler_path
                        .canonicalize()
                        .unwrap()
                        .to_string_lossy()
                        .into_owned(),
                    filter: None,
                    package_id: "owner/tool".into(),
                    activated_at: "now".into(),
                },
                HookBindingRecord {
                    id: "owner/tool/filtered".into(),
                    event: "pre_prompt".into(),
                    handler: filtered_handler_path
                        .canonicalize()
                        .unwrap()
                        .to_string_lossy()
                        .into_owned(),
                    filter: Some("false".into()),
                    package_id: "owner/tool".into(),
                    activated_at: "now".into(),
                },
                HookBindingRecord {
                    id: "owner/tool/pwd".into(),
                    event: "env_change".into(),
                    handler: env_handler_path
                        .canonicalize()
                        .unwrap()
                        .to_string_lossy()
                        .into_owned(),
                    filter: Some("PWD".into()),
                    package_id: "owner/tool".into(),
                    activated_at: "now".into(),
                },
            ],
            ..HookProfile::default()
        };
        profile.save(root).unwrap();
        std::fs::write(
            &generated_path,
            generate_hook_autoload_content(&profile, &profile_path).unwrap(),
        )
        .unwrap();

        let script = format!(
            "$env.config = ($env.config | upsert hooks {{ pre_prompt: [{{|| print 'user-hook-ran' }}] }}); source {}; print ($__numan_profile == $__numan_expected); do $env.config.hooks.pre_prompt.0; do $env.config.hooks.pre_prompt.1; do $env.config.hooks.pre_prompt.2; do $env.config.hooks.env_change.PWD.0 old new",
            nu_path_literal(&generated_path.to_string_lossy()).unwrap()
        );
        let output = std::process::Command::new(&nu)
            .args(["-n", "-c", &script])
            .output()
            .unwrap();
        assert!(
            output.status.success(),
            "Nu failed: {}\nstdout: {}",
            String::from_utf8_lossy(&output.stderr),
            String::from_utf8_lossy(&output.stdout)
        );
        let stdout = String::from_utf8_lossy(&output.stdout);
        assert!(stdout.contains("true"), "profile guard mismatch: {stdout}");
        assert!(stdout.contains("user-hook-ran"), "{stdout}");
        assert_eq!(stdout.matches("numan-handler-ran").count(), 1, "{stdout}");
        assert!(!stdout.contains("filtered-handler-ran"), "{stdout}");
        assert!(stdout.contains("env-change-handler-ran"), "{stdout}");

        let mut diverged = profile;
        diverged.bindings[0].id = "owner/tool/changed".into();
        diverged.save(root).unwrap();
        let fail_closed_script = format!(
            "$env.config = ($env.config | upsert hooks {{ pre_prompt: [{{|| print 'user-hook-ran' }}] }}); source {}; print ($env.config.hooks.pre_prompt | length); do $env.config.hooks.pre_prompt.0",
            nu_path_literal(&generated_path.to_string_lossy()).unwrap()
        );
        let output = std::process::Command::new(&nu)
            .args(["-n", "-c", &fail_closed_script])
            .output()
            .unwrap();
        assert!(
            output.status.success(),
            "Nu failed: {}",
            String::from_utf8_lossy(&output.stderr)
        );
        let stdout = String::from_utf8_lossy(&output.stdout);
        assert!(stdout.contains("1\nuser-hook-ran"), "{stdout}");
        assert!(!stdout.contains("numan-handler-ran"), "{stdout}");

        let mut wrong_identity = HookProfile::load(root).unwrap();
        wrong_identity.nu_version = Some("0.0.0".into());
        wrong_identity.save(root).unwrap();
        std::fs::write(
            &generated_path,
            generate_hook_autoload_content(&wrong_identity, &profile_path).unwrap(),
        )
        .unwrap();
        let output = std::process::Command::new(&nu)
            .args(["-n", "-c", &fail_closed_script])
            .output()
            .unwrap();
        assert!(
            output.status.success(),
            "Nu failed: {}",
            String::from_utf8_lossy(&output.stderr)
        );
        let stdout = String::from_utf8_lossy(&output.stdout);
        assert!(stdout.contains("1\nuser-hook-ran"), "{stdout}");
        assert!(!stdout.contains("numan-handler-ran"), "{stdout}");

        let mut missing_executable = HookProfile::load(root).unwrap();
        missing_executable.nu_executable = None;
        missing_executable.save(root).unwrap();
        std::fs::write(
            &generated_path,
            generate_hook_autoload_content(&missing_executable, &profile_path).unwrap(),
        )
        .unwrap();
        let output = std::process::Command::new(&nu)
            .args(["-n", "-c", &fail_closed_script])
            .output()
            .unwrap();
        assert!(
            output.status.success(),
            "Nu failed on null executable identity: {}",
            String::from_utf8_lossy(&output.stderr)
        );
        let stdout = String::from_utf8_lossy(&output.stdout);
        assert!(stdout.contains("1\nuser-hook-ran"), "{stdout}");
        assert!(!stdout.contains("numan-handler-ran"), "{stdout}");
    }
}
